const dictionaries: Record<Locale, Record<Key, string>> = { en, ar }

function stored(): Locale {
  try {
    return localStorage.getItem('locale') === 'ar' ? 'ar' : 'en'
  } catch {
    return 'en'
  }
}

export const locale = ref<Locale>(stored())

export function setLocale(next: Locale): void {
  locale.value = next
  document.documentElement.lang = next
  document.documentElement.dir = next === 'ar' ? 'rtl' : 'ltr'
  try {
    localStorage.setItem('locale', next)
  } catch {
    // Storage may be blocked; the choice then lasts only for this page load.
  }
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  return dictionaries[locale.value][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''))
}

export function formatTime(iso: string): string {
  return new Date(iso).toLocaleString(locale.value === 'ar' ? 'ar-AE' : 'en-GB')
}

export function formatAge(iso: string): string {
  const minutes = Math.max(0, Math.floor((Date.now() - new Date(iso).getTime()) / 60_000))
  if (minutes < 60) return t('ageMin', { n: minutes })
  const hours = Math.floor(minutes / 60)
  if (hours < 24) {
    const rest = minutes % 60
    return rest === 0 ? t('ageHour', { n: hours }) : t('ageHourMin', { h: hours, m: rest })
  }
  return t('ageDay', { n: Math.floor(hours / 24) })
}
