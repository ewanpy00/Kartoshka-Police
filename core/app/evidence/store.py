"""Append-only, hash-chained evidence records (ARCHITECTURE.md 1.5).

Each row stores the SHA-256 of the previous row and its own hash over (previous hash + canonical JSON of
the payload). Rows are numbered by `seq` under a transaction-level advisory lock, so two workers cannot
fork the chain. The database rejects UPDATE and DELETE on the table (migration 0002).
"""
import hashlib
import json
import uuid
from pathlib import Path

from sqlalchemy import select, text
from sqlalchemy.orm import Session

from app.config import get_settings
from app.models import Artifact, Evidence

CHAIN_LOCK = 7_301_001
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def canonical(payload: dict) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)


def row_hash(prev_hash: str | None, payload: dict) -> str:
    return hashlib.sha256(((prev_hash or "") + canonical(payload)).encode("utf-8")).hexdigest()


def new_evidence_id() -> str:
    return f"ev_{uuid.uuid4().hex[:24]}"


def seq_is_generated() -> bool:
    """True when the database assigns `evidence.seq` (an identity column or a default), so the code must not."""
    column = Evidence.__table__.c.seq
    return column.identity is not None or column.server_default is not None or column.autoincrement is True


def append(session: Session, check_id: str, domain: str | None, payload: dict, artifacts: list[dict] = ()) -> Evidence:
    """Add one record at the end of the chain. The caller commits.

    The transaction-level advisory lock is taken first and held until commit, so two workers cannot read the
    same last row and fork the chain. `seq` is assigned here under the lock, unless the column is generated by
    the database; then the database assigns it (also under the lock) and the chain order is by `seq` either way.
    """
    payload = json.loads(canonical(payload))
    session.execute(text("SELECT pg_advisory_xact_lock(:key)"), {"key": CHAIN_LOCK})
    last = session.execute(select(Evidence.seq, Evidence.hash).order_by(Evidence.seq.desc()).limit(1)).first()
    prev_hash = last[1] if last else None
    fields = {}
    if not seq_is_generated():
        fields["seq"] = last[0] + 1 if last else 1
    evidence = Evidence(
        id=new_evidence_id(), check_id=check_id, domain=domain,
        prev_hash=prev_hash, hash=row_hash(prev_hash, payload), payload=payload, **fields,
    )
    session.add(evidence)
    session.flush()
    for item in artifacts:
        session.add(Artifact(evidence_id=evidence.id, kind=item["kind"], sha256=item["sha256"], path=item["path"]))
    return evidence


def verify(session: Session, limit: int | None = None) -> dict:
    """Recompute the chain from the first row and name the first broken one.

    `first_broken` is {id, seq, reason} with reason `prev_hash_mismatch` (the link to the row before) or
    `payload_hash_mismatch` (the stored hash is not the hash of the stored payload).
    """
    prev_hash, rows = None, 0
    query = select(Evidence).order_by(Evidence.seq)
    if limit:
        query = query.limit(limit)
    for evidence in session.scalars(query):
        rows += 1
        reason = None
        if evidence.prev_hash != prev_hash:
            reason = "prev_hash_mismatch"
        elif evidence.hash != row_hash(prev_hash, evidence.payload):
            reason = "payload_hash_mismatch"
        if reason:
            return {"ok": False, "intact": False, "rows": rows, "count": rows, "broken_at": evidence.seq,
                    "first_broken": {"id": evidence.id, "seq": evidence.seq, "reason": reason}}
        prev_hash = evidence.hash
    return {"ok": True, "intact": True, "rows": rows, "count": rows, "broken_at": None, "first_broken": None, "head": prev_hash}


def screenshot_artifact(session: Session, evidence_id: str) -> Artifact | None:
    return session.scalar(select(Artifact).where(Artifact.evidence_id == evidence_id, Artifact.kind == "screenshot")
                          .order_by(Artifact.id).limit(1))


def screenshot_png(session: Session, evidence_id: str) -> bytes | None:
    """The stored phone screenshot, only when its path resolves inside the captures directory and the
    file really begins with the PNG signature. Anything else returns None."""
    artifact = screenshot_artifact(session, evidence_id)
    if artifact is None:
        return None
    root = Path(get_settings().captures_dir).resolve()
    path = Path(artifact.path).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        return None
    data = path.read_bytes()
    return data if data.startswith(PNG_SIGNATURE) else None
